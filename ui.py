@st.cache_resource
def resources() -> tuple[Settings, RuntimeServices]:
    settings = get_settings()
    configure_file_logging(LOG_DIRECTORY, settings.log_level)
    return settings, create_runtime(settings)

try:
    settings, services = resources()
except Exception as error:
    st.error(f"ShopSense could not start: {error}")
    st.stop()

trace_label = (
    "Langfuse trace ID"
    if services.langfuse is not None
    else "Trace ID (Langfuse is disabled)"
)


def clear_session() -> None:
    for key in ("access_token", "user_id", "role", "messages"):
        st.session_state.pop(key, None)


def set_authenticated_session(token: str) -> bool:
    try:
        claims = jwt.decode(
            token,
            settings.jwt_secret.get_secret_value(),
            algorithms=["HS256"],
            issuer=JWT_ISSUER,
            audience=JWT_AUDIENCE,
            options={"require": ["sub", "exp", "iat", "jti", "iss", "aud"]},
        )
    except jwt.InvalidTokenError:
        return False
    if not isinstance(claims.get("sub"), str) or not isinstance(claims.get("role"), str):
        return False
    st.session_state.access_token = token
    st.session_state.user_id = claims["sub"]
    st.session_state.role = claims["role"]
    st.session_state.setdefault("conversation_id", str(uuid.uuid4()))
    st.session_state.setdefault("thread_id", uuid.uuid4().hex[:12])
    st.session_state.setdefault("session_id", str(uuid.uuid4()))
    st.session_state.setdefault("messages", [])
    return True


def login_view() -> None:
    st.info("Paste a shopper JWT generated by `python scripts/get_user_jwt.py`.")
    with st.form("jwt-login"):
        token = st.text_input("Shopper JWT", type="password")
        token_submitted = st.form_submit_button("Sign in", type="primary")
    if token_submitted:
        if set_authenticated_session(token.strip()):
            st.rerun()
        st.error("The JWT is invalid or expired.")


if not st.session_state.get("access_token"):
    login_view()
    st.stop()

if not set_authenticated_session(st.session_state.access_token):
    clear_session()
    st.warning("Your session expired. Sign in again.")
    st.rerun()

with st.sidebar:
    st.caption(f"Signed in as `{st.session_state.user_id}`")
    st.caption(f"Thread ID: `{st.session_state.thread_id}`")
    if st.button("Start new conversation"):
        st.session_state.conversation_id = str(uuid.uuid4())
        st.session_state.thread_id = uuid.uuid4().hex[:12]
        st.session_state.session_id = str(uuid.uuid4())
        st.session_state.messages = []
        st.rerun()
    if st.button("Sign out"):
        clear_session()
        st.rerun()

for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])
        if message.get("trace_id"):
            st.caption(f"{trace_label}: `{message['trace_id']}`")


async def run_turn(message: str, user_jwt: str, trace_id: str) -> dict:
    thread_id = st.session_state.thread_id
    user_id = st.session_state.user_id
    workflow_input = {
        "user_id": user_id,
        "conversation_id": st.session_state.conversation_id,
        "thread_id": thread_id,
        "session_id": st.session_state.session_id,
        "turn_id": str(uuid.uuid4()),
        "message": message,
        "query_type": "auto",
    }
    graph_config = {
        "configurable": {"thread_id": thread_id},
        "metadata": {
            "user_id": user_id,
            "thread_id": thread_id,
            "trace_id": trace_id,
            "conversation_id": st.session_state.conversation_id,
            "session_id": st.session_state.session_id,
        },
    }
    callback = get_callback_handler(services.langfuse)
    if callback is not None:
        graph_config["callbacks"] = [callback]
    with bind_thread_id(thread_id), bind_trace_id(trace_id):
        logger.info("User request accepted input=%r", redact_pii(message)[:2000])
        try:
            with trace_turn(
                services.langfuse,
                user_id=user_id,
                thread_id=thread_id,
                trace_id=trace_id,
                message=message,
            ) as trace:
                stage = "input_guardrail"
                try:
                    logger.info("Input guardrail started")
                    if services.langfuse is None:
                        is_allowed = await assess_message(
                            message,
                            services.workflow.llm,
                        )
                    else:
                        with services.langfuse.start_as_current_observation(
                            as_type="guardrail",
                            name="input-guardrail",
                            input={
                                "message": redact_sensitive_data(message),
                            },
                        ) as guardrail_span:
                            try:
                                is_allowed = await assess_message(
                                    message,
                                    services.workflow.llm,
                                )
                            except Exception as error:
                                guardrail_span.update(
                                    level="ERROR",
                                    status_message=type(error).__name__,
                                    output={"error_type": type(error).__name__},
                                )
                                raise
                            guardrail_span.update(output={"allowed": is_allowed})
                    if not is_allowed:
                        logger.info("Input guardrail blocked request")
                        if trace is not None:
                            trace.update(
                                output={
                                    "status": "blocked",
                                    "stage": "input_guardrail",
                                }
                            )
                        return {
                            "status": "blocked",
                            "answer": "",
                            "sources": [],
                        }
                    logger.info("Input guardrail allowed request")
                    stage = "workflow"
                    async with checkpoint_context(checkpoint_file()) as saver:
                        services.workflow.compile(saver)
                        result = await services.workflow.graph.ainvoke(
                            workflow_input,
                            graph_config,
                            context={"user_jwt": user_jwt, "trace_id": trace_id},
                        )
                except Exception as error:
                    logger.exception(
                        "Turn failed stage=%s error_type=%s",
                        stage,
                        type(error).__name__,
                    )
                    if trace is not None:
                        trace.update(
                            level="ERROR",
                            status_message=type(error).__name__,
                            output={
                                "status": "error",
                                "error_type": type(error).__name__,
                            },
                        )
                    raise
                if trace is not None:
                    trace.update(
                        output=redact_sensitive_data(
                            {
                                "intent": result.get("intent"),
                                "status": result.get("status"),
                                "answer": result.get("answer", ""),
                            }
                        )
                    )
                return result
        finally:
            flush_observability(services.langfuse)


prompt = st.chat_input("How can I help with your order or store policy?")
if prompt:
    trace_id = uuid.uuid4().hex
    try:
        cleaned_message = validate_message(prompt, settings.max_message_chars)
        safe_message = redact_pii(cleaned_message)
    except Exception as error:
        st.error(f"That message could not be processed: {error}")
        st.stop()

    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    try:
        result = asyncio.run(run_turn(safe_message, st.session_state.access_token, trace_id))
        if result.get("status") == "blocked":
            st.warning(
                "I can help with orders, refunds, and store policies. "
                "Please rephrase your request."
            )
            st.caption(f"{trace_label}: `{trace_id}`")
            st.stop()
        answer = validate_answer(
            result.get("answer", ""),
            result.get("guardrail_facts"),
        )
    except Exception:
        with bind_thread_id(st.session_state.thread_id), bind_trace_id(trace_id):
            logger.exception("Turn failed before completion")
        st.error(
            "The assistant could not complete this request. "
            f"Trace ID: `{trace_id}`. Check the thread log in `logs/` and "
            "search this trace ID in Langfuse if configured."
        )
        st.stop()

    st.session_state.messages.append(
        {"role": "assistant", "content": answer, "trace_id": trace_id}
    )
    with st.chat_message("assistant"):
        st.markdown(answer)
        if result.get("sources"):
            st.caption("Policy sources: " + ", ".join(result["sources"]))
        st.caption(f"{trace_label}: `{trace_id}`")
    logger.info(
        "Assistant response ready intent=%s status=%s output=%r",
        result.get("intent"),
        result.get("status"),
        redact_pii(answer)[:2000],
    )
